# -*- coding: utf-8 -*-
import os
import tempfile
import unittest
from datetime import date, timezone, timedelta

import helpers as H
from til_drafter.transcripts import (
    clean_text, load_entries, parse_timestamp, parse_tz_offset, to_local, parse_date,
)

KST = timezone(timedelta(hours=9))
DAY = date(2026, 3, 10)


class TimestampTests(unittest.TestCase):
    def test_parse_variants(self):
        a = parse_timestamp("2026-03-10T01:02:03.456Z")
        self.assertEqual((a.hour, a.microsecond), (1, 456000))
        self.assertEqual(parse_timestamp("2026-03-10T01:02:03Z").second, 3)
        b = parse_timestamp("2026-03-10T10:00:00+09:00")
        self.assertEqual(b.astimezone(timezone.utc).hour, 1)
        c = parse_timestamp("2026-03-10T01:02:03.1234567890Z")  # 길이가 긴 소수부
        self.assertEqual(c.microsecond, 123456)

    def test_parse_invalid(self):
        for v in [None, 123, "", "yesterday", "2026-13-40T00:00:00Z"]:
            self.assertIsNone(parse_timestamp(v))

    def test_tz_offset(self):
        self.assertEqual(parse_tz_offset("+09:00"), KST)
        self.assertEqual(parse_tz_offset("9"), KST)
        self.assertEqual(parse_tz_offset("-5").utcoffset(None), timedelta(hours=-5))
        self.assertEqual(parse_tz_offset("+0530").utcoffset(None), timedelta(hours=5, minutes=30))
        self.assertIsNone(parse_tz_offset(None))
        with self.assertRaises(ValueError):
            parse_tz_offset("abc")

    def test_parse_date(self):
        self.assertEqual(parse_date("2026-03-10"), DAY)
        with self.assertRaises(ValueError):
            parse_date("2026/03/10")


class CleanTextTests(unittest.TestCase):
    def test_noise(self):
        self.assertIsNone(clean_text("Caveat: The messages below were generated by the user"))
        self.assertIsNone(clean_text("<system-reminder>be nice</system-reminder>"))
        self.assertIsNone(clean_text("<command-name>/clear</command-name>"))
        self.assertIsNone(clean_text("<local-command-stdout>ok</local-command-stdout>"))
        self.assertIsNone(clean_text("   "))
        self.assertIsNone(clean_text(None))
        self.assertIsNone(clean_text("<system-reminder>unterminated"))

    def test_reminder_block_stripped_from_real_text(self):
        t = clean_text("로그인 버그 고쳐줘\n<system-reminder>injected</system-reminder>")
        self.assertEqual(t, "로그인 버그 고쳐줘")

    def test_normal(self):
        self.assertEqual(clean_text("  hello  "), "hello")


class LoadEntriesTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.root = self._tmp.name
        self.addCleanup(self._tmp.cleanup)

    def path(self, *p):
        return os.path.join(self.root, *p)

    def test_date_filter_uses_requested_timezone(self):
        # 2026-03-09T16:00Z = KST 03-10 01:00 / 2026-03-10T14:59Z = KST 03-10 23:59 / 15:00Z = KST 03-11 00:00
        H.write_jsonl(self.path("p1", "s.jsonl"), [
            H.user("2026-03-09T14:59:59Z", "전날 23:59 KST"),
            H.user("2026-03-09T16:00:00Z", "당일 01:00 KST"),
            H.user("2026-03-10T14:59:59Z", "당일 23:59 KST"),
            H.user("2026-03-10T15:00:00Z", "다음날 00:00 KST"),
        ])
        got = load_entries(self.root, DAY, KST)
        self.assertEqual([e.texts[0] for e in got], ["당일 01:00 KST", "당일 23:59 KST"])
        utc = load_entries(self.root, DAY, timezone.utc)
        self.assertEqual([e.texts[0] for e in utc], ["당일 23:59 KST", "다음날 00:00 KST"])

    def test_default_timezone_is_system_local(self):
        H.write_jsonl(self.path("p1", "s.jsonl"), [H.user("2026-03-10T12:00:00Z", "정오")])
        local_day = to_local(__import__("til_drafter.transcripts", fromlist=["x"]).parse_timestamp("2026-03-10T12:00:00Z")).date()
        self.assertEqual(len(load_entries(self.root, local_day)), 1)

    def test_malformed_and_foreign_lines_do_not_crash(self):
        stats = {}
        H.write_jsonl(self.path("p1", "s.jsonl"), [
            "{not json at all",
            "",
            "[1,2,3]",
            '"just a string"',
            "null",
            '{"type":"user","timestamp":"2026-03-10T01:00:00Z"}',  # message 없음
            '{"type":"user","timestamp":"bad","message":{"role":"user","content":"x"}}',
            '{"type":"user","message":{"role":"user","content":"timestamp 없음"}}',
            '{"type":"user","timestamp":"2026-03-10T01:00:00Z","message":"문자열"}',
            '{"type":"user","timestamp":"2026-03-10T01:00:00Z","message":{"content":42}}',
            {"type": "summary", "summary": "x", "leafUuid": "y"},
            {"type": "system", "timestamp": "2026-03-10T01:00:00Z", "content": "sys"},
            {"type": "file-history-snapshot", "snapshot": {}},
            H.user("2026-03-10T01:00:00Z", "정상 프롬프트"),
            '{"type":"user","timestamp":"2026-03-10T01:00:00Z","message":{"role":"user","content":[1,null,"str",{"type":"text"}]}}',
            '{"truncated": ',
        ])
        got = load_entries(self.root, DAY, timezone.utc, stats)
        texts = [t for e in got for t in e.texts]
        self.assertEqual(texts, ["정상 프롬프트", "str"])
        self.assertGreaterEqual(stats["malformed"], 3)

    def test_invalid_utf8_bytes_tolerated(self):
        p = self.path("p1", "s.jsonl")
        os.makedirs(os.path.dirname(p))
        with open(p, "wb") as fh:
            fh.write(b'\xff\xfe broken line\n')
            fh.write(('{"type":"user","timestamp":"2026-03-10T01:00:00Z","cwd":"/w/a","sessionId":"s",'
                      '"message":{"role":"user","content":"ok"}}\n').encode("utf-8"))
        self.assertEqual(len(load_entries(self.root, DAY, timezone.utc)), 1)

    def test_tool_result_and_injected_text_skipped(self):
        H.write_jsonl(self.path("p1", "s.jsonl"), [
            H.user("2026-03-10T01:00:00Z", "진짜 요청"),
            H.tool_result("2026-03-10T01:00:05Z", "파일 내용 ..."),
            H.user("2026-03-10T01:00:06Z", "<system-reminder>x</system-reminder>"),
            H.user("2026-03-10T01:00:07Z", "Caveat: ignore"),
            H.user("2026-03-10T01:00:08Z", "메타", isMeta=True),
            H.user("2026-03-10T01:00:09Z", "서브에이전트", isSidechain=True),
            H.user("2026-03-10T01:00:10Z", "This session is being continued from a previous conversation..."),
            H.assistant("2026-03-10T01:00:11Z", [{"type": "thinking", "thinking": "hmm"}]),
        ])
        got = load_entries(self.root, DAY, timezone.utc)
        self.assertEqual([t for e in got for t in e.texts], ["진짜 요청"])

    def test_assistant_blocks_and_tools(self):
        H.write_jsonl(self.path("p1", "s.jsonl"), [
            H.assistant("2026-03-10T01:00:00Z", [
                {"type": "text", "text": "수정할게요"},
                H.tool_use("Edit", file_path="/w/a/b.py", old_string="x", new_string="y"),
                H.tool_use("Bash", command="ls"),
            ]),
        ])
        (e,) = load_entries(self.root, DAY, timezone.utc)
        self.assertEqual(e.role, "assistant")
        self.assertEqual(e.texts, ["수정할게요"])
        self.assertEqual([t[0] for t in e.tools], ["Edit", "Bash"])

    def test_subagent_dirs_skipped_and_results_sorted(self):
        H.write_jsonl(self.path("p1", "a.jsonl"), [H.user("2026-03-10T05:00:00Z", "늦게", sid="a")])
        H.write_jsonl(self.path("p2", "b.jsonl"), [H.user("2026-03-10T01:00:00Z", "일찍", sid="b")])
        H.write_jsonl(self.path("p1", "a", "subagents", "agent-1.jsonl"),
                      [H.user("2026-03-10T03:00:00Z", "서브")])
        got = load_entries(self.root, DAY, timezone.utc)
        self.assertEqual([e.texts[0] for e in got], ["일찍", "늦게"])

    def test_missing_dir_and_empty(self):
        self.assertEqual(load_entries(self.path("nope"), DAY), [])
        self.assertEqual(load_entries(self.root, DAY), [])

    def test_old_files_skipped_by_mtime(self):
        p = H.write_jsonl(self.path("p1", "old.jsonl"), [H.user("2026-03-10T01:00:00Z", "x")])
        old = 1_000_000_000  # 2001년
        os.utime(p, (old, old))
        self.assertEqual(load_entries(self.root, DAY, timezone.utc), [])

    def test_session_id_falls_back_to_filename(self):
        d = H.user("2026-03-10T01:00:00Z", "hi")
        del d["sessionId"]
        H.write_jsonl(self.path("p1", "abc-session.jsonl"), [d])
        (e,) = load_entries(self.root, DAY, timezone.utc)
        self.assertEqual(e.session_id, "abc-session")


if __name__ == "__main__":
    unittest.main()
