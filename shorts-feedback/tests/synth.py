"""테스트용 가짜 댓글 생성기 (결정적). 주제 4개를 섞고 정답 라벨을 함께 돌려준다.

댓글마다 주제어 3~4개(조사가 붙음)와 모든 주제에 공통인 군더더기 표현을 섞는다.
"""
import random

TOPICS = {
    "직장": ["상사", "팀장님", "회사", "퇴사", "야근", "월급", "동료", "부장", "인사팀", "회식", "연봉", "이직"],
    "시댁": ["시어머니", "시댁", "명절", "며느리", "남편", "육아", "제사", "시누이", "친정", "손주", "김장", "용돈"],
    "연애": ["전남친", "결혼식", "이별", "환승", "여자친구", "바람", "소개팅", "청첩장", "커플링", "고백", "썸", "헤어짐"],
    "이웃": ["층간소음", "윗집", "아랫집", "이웃", "관리사무소", "경비", "주차", "택배", "쓰레기", "엘리베이터", "복도", "민원"],
}
PARTICLES = ["", "", "이", "가", "은", "는", "을", "를", "에서", "랑", "도", "때문에"]
FILLER = ["진짜", "와", "아니", "솔직히", "근데", "너무", "계속", "결국", "정말", "그냥", "어떻게 됐나요", "공감돼요",
          "속상하네요", "다음 편 기대할게요", "잘 봤습니다", "이런 사연", "대박", "화나요", "걱정돼요", "응원합니다",
          "저도 그랬어요", "이해가 안 돼요", "말이 되나요", "끝까지 보세요", "후기 궁금해요", "힘내세요"]


def make_comments(n_per_topic=50, seed=3):
    rng = random.Random(seed)
    rows = []
    for label, nouns in TOPICS.items():
        for _ in range(n_per_topic):
            words = [w + rng.choice(PARTICLES) for w in rng.sample(nouns, rng.choice((3, 3, 4)))]
            words += rng.sample(FILLER, rng.choice((1, 2)))
            rng.shuffle(words)
            rows.append((" ".join(words), label))
    rng.shuffle(rows)
    return [r[0] for r in rows], [r[1] for r in rows]
